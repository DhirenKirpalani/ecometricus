// ─── Helper: flatten all keys for the translation manager ───────────────────
export function getAllTranslationKeys(): { section: string; key: string; en: string; es: string }[] {
  const result: { section: string; key: string; en: string; es: string }[] = [];
  for (const [section, entries] of Object.entries(translations)) {
    for (const [key, val] of Object.entries(entries)) {
      result.push({ section, key, en: val.en, es: val.es });
    }
  }
  return result;
}
